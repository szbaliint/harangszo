-- Used by the import job to refresh importance_auto of OpenStreetMap churches without touching anything else.
create or replace function public.set_church_importance(rows jsonb) returns integer
language sql security invoker set search_path = public as $$
  with u as (
    update churches c set importance_auto = least(100, greatest(0, (x->>'imp')::int))
    from jsonb_array_elements(rows) x
    where c.osm_type = x->>'t' and c.osm_id = (x->>'id')::bigint and c.importance_auto is distinct from least(100, greatest(0, (x->>'imp')::int))
    returning 1)
  select count(*)::int from u;
$$;
revoke execute on function public.set_church_importance(jsonb) from public, anon, authenticated;
grant execute on function public.set_church_importance(jsonb) to service_role;

-- Inserts schedule rows given as JSON (used by save_church and import_church_schedule). Runs with the caller's rights.
create or replace function public.insert_services(cid bigint, rows jsonb) returns void
language sql security invoker set search_path = public as $$
  insert into services (church_id, kind, days, start_time, end_time, note, period, feast, valid, weeks, every, anchor, tags, celebrant, place, place_church_id, feast_skip)
    select cid, x->>'kind', array(select jsonb_array_elements_text(coalesce(x->'days','[]'::jsonb))::smallint),
           (x->>'start')::time, nullif(x->>'end','')::time, nullif(x->>'note',''),
           coalesce(nullif(x->>'period',''),'all'), nullif(x->>'feast',''), nullif(x->>'valid',''),
           case when jsonb_typeof(x->'weeks') = 'array' and jsonb_array_length(x->'weeks') > 0
                then array(select jsonb_array_elements_text(x->'weeks')::smallint) end,
           case when coalesce((x->>'every')::int, 1) >= 2 and nullif(x->>'anchor','') is not null then (x->>'every')::smallint end,
           case when coalesce((x->>'every')::int, 1) >= 2 then nullif(x->>'anchor','')::date end,
           case when jsonb_typeof(x->'tags') = 'array' and jsonb_array_length(x->'tags') > 0
                then array(select distinct jsonb_array_elements_text(x->'tags')) end,
           nullif(btrim(x->>'celebrant'),''), nullif(btrim(x->>'place'),''),
           nullif(nullif(x->>'place_church_id','')::bigint, cid), coalesce((x->>'feast_skip')::boolean, false)
    from jsonb_array_elements(coalesce(rows,'[]'::jsonb)) x;
$$;
revoke execute on function public.insert_services(bigint, jsonb) from public, anon;
grant execute on function public.insert_services(bigint, jsonb) to authenticated, service_role;

-- Times for given dates, from a parish's own weekly schedule (e.g. the Franciscans' weekly PDF). On a date that has
-- rows here, they replace the regular rules for that church; other dates keep the rules.
create table if not exists public.dated_services (
  id          bigint generated by default as identity primary key,
  church_id   bigint not null references public.churches(id) on delete cascade,
  date        date not null,
  kind        text not null constraint dated_services_kind_check check (kind in ('mass','confession','adoration','rorate','prayer')),
  start_time  time not null,
  end_time    time,
  note        text,
  tags        text[] constraint dated_services_tags_check check (tags is null or array_to_string(tags, ' ') ~ '^((lang:[a-z]{2,3}|family|student|youth|university|guitar|organ|choir|silent|vigil|word|confession|traditional|irregular|solemn)( |$))+$'),
  celebrant   text constraint dated_services_celebrant_check check (celebrant is null or char_length(celebrant) between 1 and 80),
  place       text,
  place_church_id bigint references public.churches(id) on delete set null,
  source      text not null default 'manual',
  source_url  text,
  constraint dated_services_place_check check ((place is null or char_length(place) between 1 and 120) and (place_church_id is null or place_church_id <> church_id))
);
create index if not exists dated_services_church_date_idx on public.dated_services (church_id, date);
