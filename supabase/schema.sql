-- Harangszó database schema for Supabase (PostgreSQL).
-- Run once in the Supabase dashboard: SQL Editor → New query → paste → Run.
-- Safe to re-run: it only creates what is missing and replaces functions/policies.
-- Already ran an older version? Run the files in supabase/migrations/ instead.

-- ─── Tables ───────────────────────────────────────────────────────────────

create table if not exists public.churches (
  id              bigint generated by default as identity primary key,
  osm_type        text,                          -- 'node' | 'way' | 'relation' when imported from OpenStreetMap
  osm_id          bigint,
  name            text not null check (char_length(name) between 1 and 200),
  city            text not null default '',
  address         text not null default '',
  rite            text not null default 'rk' check (rite in ('rk','gk')),   -- római / görögkatolikus
  lat             double precision not null check (lat between -90 and 90),
  lon             double precision not null check (lon between -180 and 180),
  website         text,
  phone           text,
  notes           text,
  open_only_services boolean not null default false,  -- "csak szertartások idején nyitva"
  feast_sunday    text[] not null default '{}',     -- feasts on which the Sunday schedule applies
  importance_auto   smallint not null default 30,   -- 0–100 from the OpenStreetMap import; the map shows important churches first
  importance_manual smallint,                       -- optional override from the admin panel
  published       boolean not null default true,
  created_at      timestamptz not null default now(),
  updated_at      timestamptz not null default now(),
  unique (osm_type, osm_id),
  constraint churches_importance_check check (importance_auto between 0 and 100 and (importance_manual is null or importance_manual between 0 and 100))
);
create index if not exists churches_name_idx on public.churches (lower(name));
create index if not exists churches_city_idx on public.churches (lower(city));

create table if not exists public.opening_hours (
  id         bigint generated by default as identity primary key,
  church_id  bigint not null references public.churches(id) on delete cascade,
  days       smallint[] not null check (days <@ array[0,1,2,3,4,5,6]::smallint[] and cardinality(days) > 0),  -- 0 = vasárnap
  opens      time not null,
  closes     time not null
);
create index if not exists opening_hours_church_idx on public.opening_hours (church_id);

create table if not exists public.services (
  id          bigint generated by default as identity primary key,
  church_id   bigint not null references public.churches(id) on delete cascade,
  kind        text not null constraint services_kind_check check (kind in ('mass','confession','adoration','rorate')),  -- rorate: only during Advent
  days        smallint[] not null,
  start_time  time not null,
  end_time    time,
  note        text,
  period      text not null default 'all' constraint services_period_check check (period in ('all','summer','winter')),  -- summer/winter time only
  feast       text constraint services_feast_check check (feast is null or feast ~ '^[a-z0-9_]{1,30}$'),            -- feast-day schedule row; days ignored
  constraint services_days_check check (days <@ array[0,1,2,3,4,5,6]::smallint[] and (feast is not null or cardinality(days) > 0))
);
create index if not exists services_church_idx on public.services (church_id);

create table if not exists public.events (
  id          bigint generated by default as identity primary key,
  church_id   bigint not null references public.churches(id) on delete cascade,
  date        date not null,
  start_time  time,
  title       text not null check (char_length(title) between 1 and 200),
  note        text
);
create index if not exists events_church_date_idx on public.events (church_id, date);

create table if not exists public.suggestions (
  id          bigint generated by default as identity primary key,
  church_id   bigint references public.churches(id) on delete cascade,
  type        text not null check (type in ('conf','mass','hours','event','place')),
  text        text not null check (char_length(text) between 5 and 600),
  contact     text check (contact is null or char_length(contact) <= 200),
  status      text not null default 'pending' check (status in ('pending','approved','rejected')),
  created_at  timestamptz not null default now(),
  decided_at  timestamptz,
  decided_by  uuid
);
create index if not exists suggestions_status_idx on public.suggestions (status, created_at desc);

-- Staff: who may edit. role 'admin' edits everything; role 'parish' edits only the churches linked in staff_churches.
create table if not exists public.staff (
  user_id       uuid primary key references auth.users(id) on delete cascade,
  role          text not null check (role in ('admin','parish')),
  display_name  text
);
create table if not exists public.staff_churches (
  user_id    uuid not null references public.staff(user_id) on delete cascade,
  church_id  bigint not null references public.churches(id) on delete cascade,
  primary key (user_id, church_id)
);

-- ─── Helper functions (bypass RLS to avoid recursion) ─────────────────────

create or replace function public.is_admin() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.staff where user_id = auth.uid() and role = 'admin');
$$;

create or replace function public.can_edit_church(cid bigint) returns boolean
language sql stable security definer set search_path = public as $$
  select public.is_admin() or exists (
    select 1 from public.staff_churches sc join public.staff s on s.user_id = sc.user_id
    where sc.user_id = auth.uid() and sc.church_id = cid and s.role = 'parish');
$$;

create or replace function public.touch_updated_at() returns trigger language plpgsql as $$
begin new.updated_at := now(); return new; end $$;
drop trigger if exists churches_touch on public.churches;
create trigger churches_touch before update on public.churches for each row execute function public.touch_updated_at();

-- ─── Row level security ───────────────────────────────────────────────────

alter table public.churches       enable row level security;
alter table public.opening_hours  enable row level security;
alter table public.services       enable row level security;
alter table public.events         enable row level security;
alter table public.suggestions    enable row level security;
alter table public.staff          enable row level security;
alter table public.staff_churches enable row level security;

-- churches
drop policy if exists churches_read   on public.churches;
drop policy if exists churches_insert on public.churches;
drop policy if exists churches_update on public.churches;
drop policy if exists churches_delete on public.churches;
create policy churches_read   on public.churches for select using (published or public.can_edit_church(id));
create policy churches_insert on public.churches for insert with check (public.is_admin());
create policy churches_update on public.churches for update using (public.can_edit_church(id)) with check (public.can_edit_church(id));
create policy churches_delete on public.churches for delete using (public.is_admin());

-- child tables: public read, editors of that church write
do $$
declare t text;
begin
  foreach t in array array['opening_hours','services','events'] loop
    execute format('drop policy if exists %1$s_read  on public.%1$s', t);
    execute format('drop policy if exists %1$s_write on public.%1$s', t);
    execute format('create policy %1$s_read  on public.%1$s for select using (true)', t);
    execute format('create policy %1$s_write on public.%1$s for all using (public.can_edit_church(church_id)) with check (public.can_edit_church(church_id))', t);
  end loop;
end $$;

-- suggestions: anyone may submit a pending one; staff read and decide
drop policy if exists suggestions_insert on public.suggestions;
drop policy if exists suggestions_read   on public.suggestions;
drop policy if exists suggestions_update on public.suggestions;
drop policy if exists suggestions_delete on public.suggestions;
create policy suggestions_insert on public.suggestions for insert
  with check (status = 'pending' and decided_at is null and decided_by is null);
create policy suggestions_read   on public.suggestions for select using (public.is_admin() or public.can_edit_church(church_id));
create policy suggestions_update on public.suggestions for update using (public.is_admin() or public.can_edit_church(church_id));
create policy suggestions_delete on public.suggestions for delete using (public.is_admin());

-- staff: you can see your own row; admins manage everything
drop policy if exists staff_read  on public.staff;
drop policy if exists staff_write on public.staff;
create policy staff_read  on public.staff for select using (user_id = auth.uid() or public.is_admin());
create policy staff_write on public.staff for all using (public.is_admin()) with check (public.is_admin());
drop policy if exists staff_churches_read  on public.staff_churches;
drop policy if exists staff_churches_write on public.staff_churches;
create policy staff_churches_read  on public.staff_churches for select using (user_id = auth.uid() or public.is_admin());
create policy staff_churches_write on public.staff_churches for all using (public.is_admin()) with check (public.is_admin());

-- Table privileges (Supabase roles). RLS above decides which rows.
