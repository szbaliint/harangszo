-- ─── Tables ───────────────────────────────────────────────────────────────

create table if not exists public.churches (
  id              bigint generated by default as identity primary key,
  osm_type        text,                          -- 'node' | 'way' | 'relation' when imported from OpenStreetMap
  osm_id          bigint,
  name            text not null check (char_length(name) between 1 and 200),
  city            text not null default '',
  address         text not null default '',
  rite            text not null default 'rk' check (rite in ('rk','gk')),   -- római / görögkatolikus
  lat             double precision not null check (lat between -90 and 90),
  lon             double precision not null check (lon between -180 and 180),
  website         text,
  phone           text,
  notes           text,
  open_only_services boolean not null default false,  -- "csak szertartások idején nyitva"
  feast_sunday    text[] not null default '{}',     -- feasts on which the Sunday schedule applies
  importance_auto   smallint not null default 30,   -- 0–100 from the OpenStreetMap import; the map shows important churches first
  importance_manual smallint,                       -- optional override from the admin panel
  schedule_note   text,                             -- public note shown with the schedule
  schedule_source text,                             -- e.g. 'szfvar' when times came from an import
  schedule_source_url text,
  schedule_updated date,                            -- the source's own "updated" date
  source_ref      text,                             -- the source's key for this church (stable across runs)
  location_approx boolean not null default false,   -- placed at the settlement centre; to check
  schedule_locked boolean not null default false,   -- checked by an editor: imports must not overwrite
  created_by      text,                             -- e.g. 'szfvar' when an import added the church
  match_confirmed boolean not null default false,   -- an editor confirmed the import's match (merge)
  published       boolean not null default true,
  parish_updated_at timestamptz,                    -- last saved by the parish itself (plebania.html)
  parish_updated_by uuid,
  photo_url       text,                             -- a photo of the church: Wikimedia Commons thumbnail or the parish's upload
  photo_credit    text,                             -- shown with it, e.g. 'Fotó: <author> · CC BY-SA 4.0 · Wikimedia Commons'
  photo_source    text,                             -- 'commons' (photo import / admin) | 'parish' (set_church_photo)
  photo_page      text,                             -- the file's page on Commons
  photo_checked_at timestamptz,                     -- last checked by the photo import
  created_at      timestamptz not null default now(),
  updated_at      timestamptz not null default now(),
  unique (osm_type, osm_id),
  constraint churches_importance_check check (importance_auto between 0 and 100 and (importance_manual is null or importance_manual between 0 and 100)),
  constraint churches_photo_check check (
    (photo_source is null or photo_source in ('commons','parish'))
    and (photo_url is null or char_length(photo_url) <= 1000)
    and (photo_credit is null or char_length(photo_credit) <= 400)
    and (photo_page is null or char_length(photo_page) <= 1000))
);
create index if not exists churches_name_idx on public.churches (lower(name));
create index if not exists churches_city_idx on public.churches (lower(city));
create index if not exists churches_lat_idx on public.churches (lat);
create unique index if not exists churches_source_ref_idx on public.churches (schedule_source, source_ref) where source_ref is not null;

create table if not exists public.opening_hours (
  id         bigint generated by default as identity primary key,
  church_id  bigint not null references public.churches(id) on delete cascade,
  days       smallint[] not null check (days <@ array[0,1,2,3,4,5,6]::smallint[] and cardinality(days) > 0),  -- 0 = vasárnap
  opens      time not null,
  closes     time not null
);
create index if not exists opening_hours_church_idx on public.opening_hours (church_id);

create table if not exists public.services (
  id          bigint generated by default as identity primary key,
  church_id   bigint not null references public.churches(id) on delete cascade,
  kind        text not null constraint services_kind_check check (kind in ('mass','confession','adoration','rorate','prayer')),  -- rorate: only during Advent; prayer: Liturgy of the Hours, rosary, Stations… (its name in note)
  days        smallint[] not null,
  start_time  time not null,
  end_time    time,
  note        text,
  period      text not null default 'all' constraint services_period_check check (period in ('all','summer','winter','summer_months','winter_months','autumn','spring','advent','christmas','lent','eastertide','school','holiday')),  -- season (see calendar.js PERIOD_INFO); `valid` overrides its dates
  valid       text constraint services_valid_check check (valid is null or valid ~ '^\d\d-\d\d/\d\d-\d\d(,\d\d-\d\d/\d\d-\d\d)*$'),  -- "MM-DD/MM-DD[,…]"
  weeks       smallint[] constraint services_weeks_check check (weeks is null or (weeks <@ array[-1,1,2,3,4,5]::smallint[] and cardinality(weeks) > 0)),  -- weeks of the month, -1 = last
  feast       text constraint services_feast_check check (feast is null or feast ~ '^[a-z0-9_]{1,30}$'),            -- feast-day schedule row; days ignored
  every       smallint constraint services_every_check check (every is null or every between 2 and 8),          -- every n-th week …
  anchor      date,                                                                                               -- … counted from a date it happens on
  tags        text[] constraint services_tags_check check (tags is null or array_to_string(tags, ' ') ~ '^((lang:[a-z]{2,3}|family|student|youth|university|guitar|organ|choir|silent|vigil|word|confession|traditional|irregular|solemn)( |$))+$'),  -- what it is like (calendar.js TAGS)
  celebrant   text constraint services_celebrant_check check (celebrant is null or char_length(celebrant) between 1 and 80),  -- who says it
  place       text,                                                                                               -- held elsewhere: chapel, cemetery…
  place_church_id bigint references public.churches(id) on delete set null,                                       -- … or at another church in the list
  feast_skip  boolean not null default false,                                                                     -- not on holy days / public holidays
  constraint services_place_check check ((place is null or char_length(place) between 1 and 120) and (place_church_id is null or place_church_id <> church_id)),
  constraint services_days_check check (days <@ array[0,1,2,3,4,5,6]::smallint[] and (feast is not null or cardinality(days) > 0)),
  constraint services_anchor_check check ((every is null) = (anchor is null))
);
create index if not exists services_church_idx on public.services (church_id);
create index if not exists services_place_church_idx on public.services (place_church_id) where place_church_id is not null;

create table if not exists public.events (
  id          bigint generated by default as identity primary key,
  church_id   bigint not null references public.churches(id) on delete cascade,
  date        date not null,
  start_time  time,
  title       text not null check (char_length(title) between 1 and 200),
  note        text
);
create index if not exists events_church_date_idx on public.events (church_id, date);

create table if not exists public.suggestions (
  id          bigint generated by default as identity primary key,
  church_id   bigint references public.churches(id) on delete cascade,
  type        text not null check (type in ('conf','mass','hours','event','place')),
  text        text not null check (char_length(text) between 5 and 600),
  contact     text check (contact is null or char_length(contact) <= 200),
  status      text not null default 'pending' check (status in ('pending','approved','rejected')),
  created_at  timestamptz not null default now(),
  decided_at  timestamptz,
  decided_by  uuid
);
create index if not exists suggestions_status_idx on public.suggestions (status, created_at desc);

-- Staff: who may edit. role 'admin' edits everything; role 'parish' edits only the churches linked in staff_churches.
create table if not exists public.staff (
  user_id       uuid primary key references auth.users(id) on delete cascade,
  role          text not null check (role in ('admin','parish')),
  display_name  text,
  email         text
);
create table if not exists public.staff_churches (
  user_id    uuid not null references public.staff(user_id) on delete cascade,
  church_id  bigint not null references public.churches(id) on delete cascade,
  primary key (user_id, church_id)
);

-- ─── Helper functions (bypass RLS to avoid recursion) ─────────────────────

create or replace function public.is_admin() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.staff where user_id = auth.uid() and role = 'admin');
$$;

create or replace function public.can_edit_church(cid bigint) returns boolean
language sql stable security definer set search_path = public as $$
  select public.is_admin() or exists (
    select 1 from public.staff_churches sc join public.staff s on s.user_id = sc.user_id
    where sc.user_id = auth.uid() and sc.church_id = cid and s.role = 'parish');
$$;

-- A photo check that changed nothing else (the photo import) is not an edit: updated_at stays.
create or replace function public.touch_updated_at() returns trigger language plpgsql as $$
begin
  if tg_table_name = 'churches' and to_jsonb(new) ->> 'photo_checked_at' is distinct from to_jsonb(old) ->> 'photo_checked_at'
     and to_jsonb(new) - 'photo_checked_at' - 'updated_at' = to_jsonb(old) - 'photo_checked_at' - 'updated_at' then
    return new;
  end if;
  new.updated_at := now(); return new;
end $$;
drop trigger if exists churches_touch on public.churches;
create trigger churches_touch before update on public.churches for each row execute function public.touch_updated_at();

