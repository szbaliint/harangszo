      new.photo_url := old.photo_url; new.photo_credit := old.photo_credit; new.photo_source := old.photo_source; new.photo_page := old.photo_page;
    end if;
  end if;
  new.parish_updated_at := now(); new.parish_updated_by := auth.uid();
  return new;
end $$;
