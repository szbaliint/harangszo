-- child tables: public read, editors of that church write
do $$
declare t text;
begin
  foreach t in array array['opening_hours','services','events'] loop
    execute format('drop policy if exists %1$s_read  on public.%1$s', t);
    execute format('drop policy if exists %1$s_write on public.%1$s', t);
    execute format('create policy %1$s_read  on public.%1$s for select using (true)', t);
    execute format('create policy %1$s_write on public.%1$s for all using (public.can_edit_church(church_id)) with check (public.can_edit_church(church_id))', t);
  end loop;
end $$;

